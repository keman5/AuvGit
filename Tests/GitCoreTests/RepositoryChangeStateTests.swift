import XCTest
@testable import GitCore

final class RepositoryChangeStateTests: XCTestCase {
    func testIgnoredActivityDirtyContentAndRefs() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        _ = try await GitProcess.run(at: root, arguments: ["init", "-b", "main"])
        _ = try await GitProcess.run(at: root, arguments: ["config", "user.name", "Test"])
        _ = try await GitProcess.run(at: root, arguments: ["config", "user.email", "test@example.invalid"])
        let repo = GitRepository(url: root)
        try "activity.log\nnode_modules/\n".write(to: root.appendingPathComponent(".gitignore"), atomically: true, encoding: .utf8)
        let file = root.appendingPathComponent("tracked.txt")
        try "initial".write(to: file, atomically: true, encoding: .utf8)
        try await repo.stage(paths: [".gitignore", "tracked.txt"])
        try await repo.commit(message: "Initial")
        let indexURL = root.appendingPathComponent(".git/index")
        let originalIndex = try Data(contentsOf: indexURL)
        let clean = try await repo.changeState(files: repo.status())
        try "log".write(to: root.appendingPathComponent("activity.log"), atomically: true, encoding: .utf8)
        try FileManager.default.createDirectory(at: root.appendingPathComponent("node_modules"), withIntermediateDirectories: true)
        try "dependency".write(to: root.appendingPathComponent("node_modules/package.js"), atomically: true, encoding: .utf8)
        let ignored = try await repo.changeState(files: repo.status())
        XCTAssertEqual(clean, ignored)
        XCTAssertEqual(try Data(contentsOf: indexURL), originalIndex)
        try "changed".write(to: file, atomically: true, encoding: .utf8)
        let dirtyFiles = try await repo.status()
        let dirty = try await repo.changeState(files: dirtyFiles)
        try "updated".write(to: file, atomically: true, encoding: .utf8)
        let dirtyAgainFiles = try await repo.status()
        let dirtyAgain = try await repo.changeState(files: dirtyAgainFiles)
        XCTAssertEqual(dirtyFiles, dirtyAgainFiles)
        XCTAssertNotEqual(dirty, dirtyAgain)
        XCTAssertEqual(clean.history, dirtyAgain.history)
        try await repo.stage(paths: ["tracked.txt"])
        let staged = try await repo.changeState(files: repo.status())
        try "restage".write(to: file, atomically: true, encoding: .utf8)
        try await repo.stage(paths: ["tracked.txt"])
        let restaged = try await repo.changeState(files: repo.status())
        XCTAssertNotEqual(staged, restaged)
        try await repo.commit(message: "Updated")
        let committed = try await repo.changeState(files: repo.status())
        XCTAssertNotEqual(clean.history, committed.history)
        _ = try await GitProcess.run(at: root, arguments: ["switch", "-c", "same-commit"])
        let switched = try await repo.changeState(files: repo.status())
        XCTAssertNotEqual(committed.history, switched.history)
    }
}
