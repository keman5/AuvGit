import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { ListRootsRequestSchema } from '@modelcontextprotocol/sdk/types.js';
import { currentRepository } from '../src/context.mjs';
import { projectFixture } from './helpers/project-fixture.mjs';
import { git } from '../src/git.mjs';

test('successive empty entrypoint calls follow fresh MCP roots, not the last opened repository', async t => {
  const parent = await realpath(await mkdtemp(path.join(tmpdir(), 'raygit-context-')));
  t.after(() => rm(parent, { recursive: true, force: true }));
  const a = path.join(parent, 'a'), b = path.join(parent, 'b');
  await git(parent, ['init', a]); await git(parent, ['init', b]);
  const executable = await projectFixture(parent, [{ name: 'Alpha', roots: [{ path: a }] }, { name: 'Beta', roots: [{ path: b }] }]);
  const env = { RAYGIT_CONFIG_DIR: path.join(parent, 'settings'), RAYGIT_CODEX_BIN: executable };
  let roots = [{ uri: pathToFileURL(a).href }], requests = 0;
  const client = new Client({ name: 'root-test', version: '1' }, { capabilities: { roots: { listChanged: true } } });
  client.setRequestHandler(ListRootsRequestSchema, async () => { requests++; return { roots }; });
  await client.connect(new StdioClientTransport({ command: 'sh', args: [path.resolve('scripts/start.sh')], cwd: parent, env }));
  t.after(() => client.close());
  const open = args => client.callTool({ name: 'raygit_open', arguments: args });
  assert.equal((await open({})).structuredContent.repo, a);
  roots = [{ uri: pathToFileURL(b).href }, { uri: pathToFileURL(parent).href }];
  const changed = (await open({})).structuredContent;
  assert.equal(changed.repo, b); assert.equal(changed.contextSource, 'roots');
  assert.equal(requests, 2);
  await open({ repo: a });
  assert.equal((await open({})).structuredContent.repo, b);
  roots = [{ uri: pathToFileURL(a).href }, { uri: pathToFileURL(b).href }];
  const ambiguous = (await open({})).structuredContent;
  assert.equal(ambiguous.repo, b); assert.equal(ambiguous.contextSource, 'recent'); assert.equal(ambiguous.projects.length, 2);
  roots = [];
  assert.equal((await open({})).structuredContent.repo, b);
  await client.close();
  const reopened = new Client({ name: 'restart-test', version: '1' });
  await reopened.connect(new StdioClientTransport({ command: 'sh', args: [path.resolve('scripts/start.sh')], cwd: parent, env }));
  t.after(() => reopened.close());
  const restored = (await reopened.callTool({ name: 'raygit_open', arguments: {} })).structuredContent;
  assert.equal(restored.repo, b); assert.equal(restored.contextSource, 'recent');
  assert.equal(restored.projects.find(p => p.repo === a).name, 'Alpha');
  const cwd = await currentRepository({ cwd: a, pluginRoot: path.resolve('.') });
  assert.equal(cwd.repo, a); assert.equal(cwd.source, 'cwd');
  assert.equal((await currentRepository({ cwd: a, pluginRoot: a })).needsRepository, true);
  assert.equal((await currentRepository({ cwd: a, listRoots: async () => { throw Error('disconnected'); } })).needsRepository, true);
});
